"""Reset the demo to a clean, known state.

Usage:  python -m scripts.reset_demo
Removes candidate memories, runs and sources; reloads the synthetic fixtures and policy memory.
"""
import time

from membrane import fixtures
from membrane.db import get_db, now


def main():
    db = get_db()
    t = now()
    db.simulation_runs.delete_many({})
    db.sources.delete_many({})
    db.memory_versions.delete_many({"_id": {"$not": {"$regex": "^policy_"}}})

    for fx in fixtures.FIXTURES:
        db.task_fixtures.replace_one({"_id": fx["_id"]}, fx, upsert=True)
    db.task_fixtures.delete_many({"_id": {"$nin": [f["_id"] for f in fixtures.FIXTURES]}})
    for mem in fixtures.policy_memory_docs(t):
        db.memory_versions.replace_one({"_id": mem["_id"]}, mem, upsert=True)
    db.sources.replace_one({"_id": fixtures.POLICY_SOURCE["_id"]},
                           {**fixtures.POLICY_SOURCE, "created_at": t}, upsert=True)

    print(f"fixtures: {db.task_fixtures.count_documents({})}, "
          f"active policy memories: {db.memory_versions.count_documents({'status': 'active'})}")

    # Wait until Vector Search can serve the fixtures again (embeddings are generated by Atlas).
    for _ in range(30):
        try:
            hits = list(db.task_fixtures.aggregate([{"$vectorSearch": {
                "index": "fixture_vec", "path": "message", "query": {"text": "refund"},
                "numCandidates": 20, "limit": 3}}]))
        except Exception as exc:
            hits = []
            print("vector search not ready:", str(exc)[:120])
        if hits:
            print("vector search ready")
            return
        time.sleep(2)
    print("WARNING: vector search returned nothing. Run `python -m scripts.setup_indexes` and retry.")


if __name__ == "__main__":
    main()
